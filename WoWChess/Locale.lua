function WC.Language()
    local selected = WC.db and WC.db.settings and WC.db.settings.language
    if selected == "es" or selected == "en" then return selected end
    local client = GetLocale and GetLocale() or "esES"
    return client:sub(1, 2) == "en" and "en" or "es"
end

function WC.SetLanguage(language)
    if language ~= "es" and language ~= "en" then return false end
    WC.db.settings.language = language
    return true
end

function WC.L(key)
    if WC.Language() == "en" then return english[key] or key end
    return key
end
